"""Build ``dist/`` for a static host (Qoder Sites) pointed at a live API.

Usage::

    uv run python scripts/export_static.py --api-base https://lab.onrender.com

The dashboard is plain ES modules with no build step; exporting is a copy plus
a rewritten ``config.js``. ``apiBase`` is public information (the API origin),
never a secret.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "frontend"
TARGET = ROOT / "dist"


def export(api_base: str, target: Path) -> dict:
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(SOURCE, target)

    config = target / "config.js"
    config.write_text(
        "/**\n"
        " * Generated by scripts/export_static.py for a static deployment.\n"
        " * The API origin is public; no secret ever belongs in this file.\n"
        " */\n"
        f"window.LAB_CONFIG = {json.dumps({'apiBase': api_base.rstrip('/'), 'refreshMs': 30000, 'title': 'Liquid Glass Crypto Lab'}, indent=2)};\n",
        encoding="utf-8",
    )

    files = sorted(str(path.relative_to(target)) for path in target.rglob("*") if path.is_file())
    return {"target": str(target), "files": len(files), "api_base": api_base}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--api-base", required=True, help="Public API origin, e.g. https://x.onrender.com")
    parser.add_argument("--out", default=str(TARGET), help="Output directory (default: dist/)")
    args = parser.parse_args()
    print(json.dumps(export(args.api_base, Path(args.out)), indent=2))


if __name__ == "__main__":
    main()
